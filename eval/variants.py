def _first_party_domains(root: Path) -> list[str]:
    counts: Counter = Counter()
    for p in root.rglob("*"):
        if p.is_file() and (p.suffix.lower() in {".har", ".html", ".htm"} or p.name == ".har"):
            text = p.read_text(encoding="utf-8", errors="ignore")
            for host in re.findall(r"https?://([a-z0-9][a-z0-9.-]+\.[a-z]{2,})", text[:5_000_000], re.I):
                if not is_boilerplate(host):
                    counts[registrable(host.lower())] += 1
            if p.suffix.lower() == ".har" and "." in p.stem:
                counts[registrable(p.stem.lower())] += 5
    return [d for d, c in counts.most_common(4) if c >= 2 and d]


def _new_domain(old: str, rng: random.Random) -> str:
    label, _, suffix = old.partition(".")
    if "-" in label:
        new = "-".join(rng.choice(WORDS) for _ in label.split("-"))
    elif any(ch.isdigit() for ch in label):
        new = rng.choice(WORDS) + str(rng.randint(10, 99))
    else:
        new = rng.choice(WORDS) + rng.choice(WORDS)
    return f"{new}.{suffix or 'com'}"


def _rewrite_text_files(root: Path, fn) -> int:
    n = 0
    for p in root.rglob("*"):
        if not p.is_file() or p.stat().st_size > 50_000_000:
            continue
        text_ext = {".har", ".html", ".htm", ".json", ".css", ".js", ".pobrane", ".txt"}
        if p.suffix.lower() in text_ext or p.name == ".har":
            raw = p.read_bytes()
            if b"\x00" in raw[:4096]:
                continue
            text = raw.decode("utf-8", errors="surrogateescape")
            new = fn(p, text)
            if new != text:
                p.write_bytes(new.encode("utf-8", errors="surrogateescape"))
                n += 1
    return n


def _images(root: Path, top_level_only: bool = False) -> list[Path]:
    out = []
    for p in sorted(root.rglob("*")):
        if p.is_file() and p.suffix.lower() in IMG_EXT:
            if top_level_only and p.parent != root:
                continue
            out.append(p)
    return out


def m_recrop(root: Path, rng: random.Random) -> str:
    from PIL import Image, ImageEnhance

    n = 0
    for p in _images(root):
        if p.parent != root and rng.random() > 0.7:
            continue
        try:
            with Image.open(p) as im:
                im = im.convert("RGB")
                w, h = im.size
                if w < 32 or h < 32:
                    continue
                dx, dy = int(w * rng.uniform(0.02, 0.07)), int(h * rng.uniform(0.02, 0.07))
                im = im.crop((dx, dy, w - dx, h - dy))
                s = rng.uniform(0.8, 1.0)
                im = im.resize((max(16, int(im.width * s)), max(16, int(im.height * s))))
                im = ImageEnhance.Brightness(im).enhance(rng.uniform(0.92, 1.08))
                buf = io.BytesIO()
                im.save(buf, format="JPEG", quality=rng.randint(65, 85))
            p.write_bytes(buf.getvalue())
            n += 1
        except Exception:  # noqa: BLE001 — svg or broken image: leave as is
            continue
    for v in [p for p in root.iterdir() if p.is_file() and p.suffix.lower() in {".mp4", ".mov", ".m4v"}]:
        n += _reencode_video(v, rng)
    return f"recrop:{n}"


def _reencode_video(path: Path, rng: random.Random, max_frames: int = 450) -> int:
    """Trim + crop + rescale a video (re-upload simulation). Returns 1 on success."""
    import cv2

    cap = cv2.VideoCapture(str(path))
    fps = cap.get(cv2.CAP_PROP_FPS) or 25.0
    ok, frame = cap.read()
    if not ok:
        cap.release()
        return 0
    h, w = frame.shape[:2]
    dx, dy = int(w * 0.04), int(h * 0.04)
    ow, oh = int((w - 2 * dx) * 0.8) // 2 * 2, int((h - 2 * dy) * 0.8) // 2 * 2
    tmp = path.with_name("tmp_" + path.stem + ".mp4")
    out = cv2.VideoWriter(str(tmp), cv2.VideoWriter_fourcc(*"mp4v"), fps, (ow, oh))
    skip = rng.randint(0, int(fps))
    k = 0
    while ok and k < max_frames + skip:
        if k >= skip:
            out.write(cv2.resize(frame[dy:h - dy, dx:w - dx], (ow, oh)))
        ok, frame = cap.read()
        k += 1
    cap.release()
    out.release()
    tmp.replace(path)
    return 1


def m_headline(root: Path, rng: random.Random) -> str:
    def swap(match: re.Match) -> str:
        inner = match.group(2)
        words = re.findall(r"\b[A-ZĄĆĘŁŃÓŚŹŻ][a-ząćęłńóśźż]{3,}\b", inner)
        for w in words[: max(1, len(words) // 2)]:
            inner = inner.replace(w, rng.choice(FICTIONAL_NAMES), 1)
        return match.group(1) + inner + match.group(3)

    def fn(p: Path, text: str) -> str:
        if p.suffix.lower() not in {".html", ".htm"}:
            return text
        return re.sub(r"(<(?:title|h1|h2)[^>]*>)(.*?)(</(?:title|h1|h2)>)", swap, text, flags=re.S | re.I)

    return f"headline:{_rewrite_text_files(root, fn)}"


def m_new_domain(root: Path, rng: random.Random) -> str:
    olds = _first_party_domains(root)
    mapping = {o: _new_domain(o, rng) for o in olds}

    def fn(p: Path, text: str) -> str:
        for o, n in mapping.items():
            text = text.replace(o, n)
        return text

    _rewrite_text_files(root, fn)
    for p in list(root.rglob("*.har")):
        for o, n in mapping.items():
            if o in p.name:
                p.rename(p.with_name(p.name.replace(o, n)))
    return "new_domain:" + ",".join(f"{o}->{n}" for o, n in mapping.items())


def m_drop_har(root: Path, rng: random.Random) -> str:
    hs = [p for p in root.rglob("*") if p.is_file() and (p.suffix.lower() == ".har" or p.name == ".har")]
    for p in hs:
        p.unlink()
    return f"drop_har:{len(hs)}"


def m_drop_landing(root: Path, rng: random.Random) -> str:
    n = 0
    for p in sorted(root.rglob("*"), key=lambda q: -len(q.parts)):
        if p.is_dir() and p.name.endswith("_files"):
            shutil.rmtree(p)
            n += 1
        elif p.is_file() and p.suffix.lower() in {".html", ".htm", ".mhtml", ".mht"}:
            p.unlink()
            n += 1
    return f"drop_landing:{n}"


