def generate_set(sample_rows: list[dict], out: Path, seed: int, per_incident: int = 3, n_public: int = 12,
                 n_clones: int = 4, ext_root: Path | None = None) -> list[dict]:
    rng = random.Random(seed)
    out.mkdir(parents=True, exist_ok=True)
    rows: list[dict] = []
    for r in sample_rows:
        src = Path(r["path"])
        for k in range(per_incident):
            recipe = RECIPES[(seed * 7 + k + zlib.crc32(r["id"].encode()) % 5) % len(RECIPES)]
            vid = f"syn-{r['id']}-s{seed}v{k}"
            try:
                path, log = make_variant(src, out / vid, recipe, rng)
            except Exception as exc:  # noqa: BLE001 — a failing mutation is reported, not fatal
                print(f"variant {vid} failed: {exc}")
                continue
            rows.append({"id": vid, "path": str(path), "label": r["label"], "group_label": r["group_label"],
                         "parent": r["id"], "kind": "variant", "synthetic": True, "mutations": log})
    rows += public_distractors(out, n_public, rng, ext_root or Path.home() / "HydraNexus/data/external-lab",
                               tag=f"-s{seed}")
    for k, r in enumerate(rng.sample(sample_rows, min(n_clones, len(sample_rows)))):
        vid = f"syn-hn-{k:02d}-s{seed}"
        log = template_clone(Path(r["path"]), out / vid, rng)
        if log:
            rows.append({"id": vid, "path": str(out / vid), "label": f"HN-{vid}", "group_label": None,
                         "parent": r["id"], "kind": "hard_negative_template", "synthetic": True, "mutations": log})
    (out / "manifest.json").write_text(json.dumps({"note": SYNTHETIC_NOTE, "seed": seed, "incidents": rows},
                                                  indent=1, ensure_ascii=False))
    return rows


