def _portrait(rng: random.Random, size: tuple[int, int]) -> bytes:
    from PIL import Image, ImageDraw

    w, h = max(64, size[0]), max(64, size[1])
    im = Image.new("RGB", (w, h), tuple(rng.randint(40, 220) for _ in range(3)))
    d = ImageDraw.Draw(im)
    skin = tuple(rng.randint(150, 235) for _ in range(3))
    d.ellipse((w * 0.3, h * 0.15, w * 0.7, h * 0.6), fill=skin)
    d.rectangle((w * 0.2, h * 0.62, w * 0.8, h), fill=tuple(rng.randint(0, 120) for _ in range(3)))
    for _ in range(30):
        x, y = rng.randint(0, w), rng.randint(0, h)
        d.point((x, y), fill=(rng.randint(0, 255),) * 3)
    buf = io.BytesIO()
    im.save(buf, format="JPEG", quality=85)
    return buf.getvalue()


def m_person_photo(root: Path, rng: random.Random) -> str:
    from PIL import Image

    n = 0
    for p in _images(root):
        if PERSON_HINT.search(p.name):
            try:
                with Image.open(p) as im:
                    size = im.size
            except Exception:  # noqa: BLE001
                size = (200, 200)
            p.write_bytes(_portrait(rng, size))
            n += 1
    return f"person_photo:{n}"


def m_language(root: Path, rng: random.Random) -> str:
    def fn(p: Path, text: str) -> str:
        if p.suffix.lower() not in {".html", ".htm"}:
            return text
        for pl, en in sorted(LANG_PL_EN.items(), key=lambda kv: -len(kv[0])):
            text = re.sub(rf"(?<=[>\s]){re.escape(pl)}(?=[\s<.,!?:])", en, text)
        return text

    return f"language:{_rewrite_text_files(root, fn)}"


