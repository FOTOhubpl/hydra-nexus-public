"""Synthetic variant generator (SYNTHETIC material, clearly labelled in every manifest and result).

From each SAMPLE incident it derives mutations the hidden test set is likely to contain (task §6: "new variants
of known campaigns and material from other campaigns"), keeping the parent's labels:

- recrop: re-cropped / resized / re-encoded images (JPEG bytes, original name kept)
- headline: changed title/headline text with the same template (names swapped)
- new_domain: first-party domains rotated, URL skeleton/trackers/paths kept
- drop_har / drop_landing / drop_creatives: missing modalities
- person_photo: person-like images replaced by a different (synthetic) portrait
- language: the same page with UI strings in another language
- near_dup / exact_dup: duplicates
- formats: zip, mhtml (html + _files → one .mhtml), rename_ext (.pobrane / .pobierz / no extension / upper
  case), har_dotname (HAR named only `.har`), nest_bundle (capture tool nesting, like incident 14),
  misfiled_har (another incident's HAR in the folder, like incident 2)

Distractors (label = their own singleton campaign): incidents built from public phishing data (PhiUSIIL,
CC BY 4.0, Prasad & Chandra 2024; PhishTank, attribution required) and "template clones" (hard negatives: a
sample page skeleton with all campaign-specific content, assets, trackers and domains removed).

The synthetic marker lives in manifest.json only (a marker file inside every folder would itself become a shared
"gene" across synthetic incidents). Output lives outside git: ~/HydraNexus/data/nask/variants/<set>/ with
manifest.json.
"""

