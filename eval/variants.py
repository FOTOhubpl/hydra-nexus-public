def _write_page_incident(dst: Path, url: str, title: str, body: str, rng: random.Random) -> None:
    dst.mkdir(parents=True, exist_ok=True)
    host = urlsplit(url).hostname or "unknown.invalid"
    html = (f"<!-- saved from url=({len(url):04d}){url} -->\n<html><head><title>{title}</title></head>"
            f"<body><h1>{title}</h1><p>{body}</p><form action=\"{url}\"><input name=\"login\"></form></body></html>")
    (dst / f"{re.sub(r'[^A-Za-z0-9]+', '_', title)[:60] or 'page'}.html").write_text(html, encoding="utf-8")
    har = {"log": {"version": "1.2", "creator": {"name": "eval-synthetic", "version": "1"}, "entries": [
        {"request": {"method": "GET", "url": url}, "response": {"status": 200, "redirectURL": ""},
         "serverIPAddress": f"203.0.113.{rng.randint(1, 254)}"}]}}
    (dst / f"{host}.har").write_text(json.dumps(har), encoding="utf-8")


def public_distractors(out: Path, n: int, rng: random.Random, ext_root: Path, tag: str = "") -> list[dict]:
    rows: list[dict] = []
    phi = ext_root / "phiusiil" / "PhiUSIIL_Phishing_URL_Dataset.csv"
    pt = ext_root / "phishtank" / "online-valid.csv"
    pool: list[tuple[str, str, str]] = []
    if phi.exists():
        with phi.open(encoding="utf-8-sig", errors="replace") as fh:
            for i, r in enumerate(csv.DictReader(fh)):
                if r.get("label") == "0" and r.get("HasTitle") == "1" and r.get("Title"):
                    pool.append((r["URL"], r["Title"][:120], "PhiUSIIL (CC BY 4.0, Prasad & Chandra 2024)"))
                if i > 120_000:
                    break
    if pt.exists():
        with pt.open(encoding="utf-8", errors="replace") as fh:
            for r in csv.DictReader(fh):
                host = urlsplit(r["url"]).hostname or "login"
                pool.append((r["url"], f"{host} – {r.get('target') or 'login'}",
                             "PhishTank (Cisco Talos, attribution required)"))
    rng.shuffle(pool)
    seen, titles, picked = set(), set(), []
    for url, title, origin in pool:  # one per registrable domain and title, so two distractors are never one site
        dom = registrable((urlsplit(url).hostname or "").lower())
        if dom and dom not in seen and title.lower() not in titles:
            seen.add(dom)
            titles.add(title.lower())
            picked.append((url, title, origin))
        if len(picked) >= n:
            break
    for k, (url, title, origin) in enumerate(picked):
        iid = f"syn-dis-{k:03d}{tag}"
        words = " ".join(w for w in re.split(r"[^A-Za-z0-9]+", urlsplit(url).path) if w)
        _write_page_incident(out / iid, url, title, words, rng)
        rows.append({"id": iid, "path": str(out / iid), "label": f"D-{iid}", "group_label": f"GD-{iid}",
                     "kind": "distractor_public", "origin": origin, "synthetic": True, "mutations": []})
    return rows


def template_clone(src: Path, dst: Path, rng: random.Random) -> list[str]:
    """Hard negative: keep the HTML tag skeleton of a sample page, replace every text node, drop assets,
    trackers, scripts, HAR and domains. Shares only the template with its source."""
    from bs4 import BeautifulSoup, NavigableString

    htmls = [p for p in src.rglob("*") if p.is_file() and p.suffix.lower() in {".html", ".htm"}]
    if not htmls:
        return []
    dst.mkdir(parents=True, exist_ok=True)
    soup = BeautifulSoup(htmls[0].read_text(encoding="utf-8", errors="replace"), "lxml")
    for t in soup(["script", "noscript", "iframe"]):
        t.decompose()
    for t in soup.find_all(True):
        for attr in ("src", "href", "action", "srcset", "data-src"):
            if attr in t.attrs:
                t[attr] = "#"
    brand = rng.choice(WORDS).capitalize() + rng.choice(WORDS).capitalize()
    for s in list(soup.find_all(string=True)):
        if isinstance(s, NavigableString) and s.strip():
            s.replace_with(" ".join(rng.choice(WORDS) for _ in range(max(1, len(s.split())))) + f" {brand}")
    for c in soup.find_all(string=lambda x: isinstance(x, str) and "saved from" in x):
        c.extract()
    (dst / f"{brand}.html").write_text(str(soup), encoding="utf-8")
    return [f"template_clone_of:{src.name}"]


