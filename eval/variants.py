def m_mhtml(root: Path, rng: random.Random) -> str:
    n = 0
    pages = [p for p in root.rglob("*") if p.is_file() and p.suffix.lower() in {".html", ".htm"}
             and not any(part.endswith("_files") for part in p.relative_to(root).parts[:-1])]
    for html in pages:
        files_dir = html.with_name(html.stem + "_files")
        msg = email.mime.multipart.MIMEMultipart("related", type="text/html")
        text = html.read_text(encoding="utf-8", errors="replace")
        m = re.search(r"saved from url=\(\d+\)(\S+?)\s*-->", text[:4000])
        part = email.mime.text.MIMEText(text, "html", "utf-8")
        part["Content-Location"] = m.group(1) if m else f"https://example.invalid/{html.name}"
        msg.attach(part)
        if files_dir.is_dir():
            for f in sorted(files_dir.rglob("*")):
                if f.is_file():
                    b = email.mime.base.MIMEBase("application", "octet-stream")
                    b.set_payload(f.read_bytes())
                    encoders.encode_base64(b)
                    b["Content-Location"] = f"https://example.invalid/assets/{f.name}"
                    msg.attach(b)
            shutil.rmtree(files_dir)
        html.with_suffix(".mhtml").write_bytes(msg.as_bytes())
        html.unlink()
        n += 1
    return f"mhtml:{n}"


