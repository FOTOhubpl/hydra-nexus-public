def _cache(root, name, data):
    p = root / "dns" / f"{name}.json"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps({"source": "dns", "key": name, "fetched_at": "2026-11-21T12:00:00+00:00",
                             "status": "ok", "data": {"answers": data}}))


def test_infra_rule_needs_capture_ip_match(settings, tmp_path):
    """Parking NS in the replay cache counts only when the cached A answer meets the IPs seen in the capture."""
    enr_dir = settings.enrich_cache
    _cache(enr_dir, "thin-fixture.pl_NS", ["ns1.parkingcrew.net."])  # lowercase keys: Linux is case-sensitive
    _cache(enr_dir, "thin-fixture.pl_A", ["45.83.200.99"])
    ctx = _ctx(settings, tmp_path)
    other = parked_incident(tmp_path, "thin-1", "thin-fixture.pl", ip="45.83.200.10", page=THIN_LANDER)
    assert parked.incident_verdict(other, ctx) is None  # capture IP differs from the resolved A: no infra rule
    same = parked_incident(tmp_path, "thin-2", "thin-fixture.pl", ip="45.83.200.99", page=THIN_LANDER)
    v = parked.incident_verdict(same, ctx)
    assert v is not None and v.rules == ["R1"] and "infra:parking-domain-ns:ns1.parkingcrew.net" in v.indicators


def test_parked_genes_downgraded_with_evidence(settings, tmp_path):
    inc = parked_incident(tmp_path, "pk-1", "alpha-fixture.pl")
    genes = run_all(inc, _ctx(settings, tmp_path), only=["inf_dom", "inf_har"]).genes
    flag = [g for g in genes if g.kind == "inf_parked"]
    assert len(flag) == 1 and flag[0].value == "parked" and level(flag[0]) == "none"
    assert "R3" in flag[0].evidence.note and flag[0].evidence.artifact_id
    by = {g.kind: g for g in genes if g.value}
    for k in ("page_title", "favicon_mmh3", "asset_sha256", "dom_skeleton_hash"):
        assert by[k].dependency_group == parked.PARKED_GROUP and level(by[k]) == "none", k
        assert "parked page template" in by[k].evidence.note
    assert by["server_ip"].dependency_group == parked.PARKED_IP_GROUP and level(by["server_ip"]) == "kit"


def test_three_parked_domains_never_same_campaign(settings, tmp_path):
    """ADOPT #13 acceptance: one parking template on unrelated domains gives no same_campaign pair."""
    ctx = _ctx(settings, tmp_path)
    doms = ["alpha-fixture.pl", "bravo-fixture.com", "charlie-fixture.net"]
    incs = {f"pk-{i}": parked_incident(tmp_path, f"pk-{i}", d) for i, d in enumerate(doms)}
    genes = {i: run_all(inc, ctx, only=["inf_dom", "inf_har"]).genes for i, inc in incs.items()}
    filler = {f"f{k}": web_incident(tmp_path / f"f{k}", f"f{k}") for k in range(5)}
    genes |= {i: run_all(inc, ctx, only=["inf_dom", "inf_har"]).genes for i, inc in filler.items()}
    rarity = build_rarity(genes, {})
    gen = {i: build_genome(i, gs, {}) for i, gs in genes.items()}
    th = Thresholds()
    for a, b in (("pk-0", "pk-1"), ("pk-0", "pk-2"), ("pk-1", "pk-2")):
        pe = score_pair(gen[a], gen[b], rarity, th)
        assert is_linked(pe, th) is None, (a, b, pe.score.hypothesis)  # neither campaign nor template group


def test_without_detector_the_template_would_link(settings, tmp_path, monkeypatch):
    """Control for the acceptance test: without the detector the same captures link as one template group."""
    monkeypatch.setattr(parked, "incident_verdict", lambda inc, ctx=None: None)
    ctx = _ctx(settings, tmp_path)
    incs = {f"pk-{i}": parked_incident(tmp_path, f"pk-{i}", d) for i, d in enumerate(["a-fx.pl", "b-fx.com"])}
    incs |= {f"f{k}": web_incident(tmp_path / f"f{k}", f"f{k}") for k in range(5)}
    genes = {i: run_all(inc, ctx, only=["inf_dom", "inf_har"]).genes for i, inc in incs.items()}
    rarity = build_rarity(genes, {})
    gen = {i: build_genome(i, gs, {}) for i, gs in genes.items()}
    th = Thresholds()
    pe = score_pair(gen["pk-0"], gen["pk-1"], rarity, th)
    assert is_linked(pe, th) == "group", pe.score.hypothesis  # shared template


