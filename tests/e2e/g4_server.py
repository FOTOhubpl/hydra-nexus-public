"""G4 scenario server: tests/e2e/server.py with an operator-chosen admin password and restart support.

    python -m tests.e2e.g4_server --root DIR --ready DIR/server.json --ui-dist ui/dist [--restart]

First start: fresh state under DIR, auth on (HYDRA_AUTH=1, HYDRA_ADMIN_PASSWORD from G4_ADMIN_PASSWORD), synthetic
corpus analysed. --restart: same DIR, no re-analysis, so the persisted SQLite/CAS state is what the API serves.
"""

from __future__ import annotations

import argparse
import json
import os
import signal
import sys
import time
from pathlib import Path

from tests.e2e import server as s

PASSWORD = os.environ.get("G4_ADMIN_PASSWORD", "G4-Scenario-Adm1n-2026")
s.E2E_ADMIN_PASSWORD = PASSWORD
s.login_session.__defaults__ = (s.E2E_ADMIN_USER, PASSWORD, 120.0)
_env = s.server_env


def _server_env(root, port, ui_dist, extra=None):  # noqa: ANN001, ANN202
    env = _env(root, port, ui_dist, extra)
    env["HYDRA_ADMIN_PASSWORD"] = PASSWORD
    return env


s.server_env = _server_env


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", type=Path, required=True)
    ap.add_argument("--ready", type=Path, required=True)
    ap.add_argument("--ui-dist", type=Path)
    ap.add_argument("--restart", action="store_true")
    a = ap.parse_args()
    if a.restart:  # the input corpus is regenerated byte-identically; only the API state (SQLite/CAS) must persist
        import shutil

        shutil.rmtree(a.root / "data" / "e2e" / "new", ignore_errors=True)
        shutil.rmtree(a.root / "data" / "g4", ignore_errors=True)
    srv = s.start(a.root, ui_dist=a.ui_dist.resolve() if a.ui_dist else None, analyse=not a.restart)
    srv.info["restarted"] = a.restart
    from tests.e2e import g4_fixtures

    srv.info["g4"] = g4_fixtures.build(srv.root / "data" / "g4", srv.base)
    a.ready.parent.mkdir(parents=True, exist_ok=True)
    a.ready.write_text(json.dumps(srv.info, indent=2))
    print(json.dumps(srv.info), flush=True)

    def _bye(*_: object) -> None:
        srv.stop()
        sys.exit(0)

    signal.signal(signal.SIGTERM, _bye)
    signal.signal(signal.SIGINT, _bye)
    while srv.proc.poll() is None:
        time.sleep(1)
    sys.exit(srv.proc.returncode or 1)


if __name__ == "__main__":
    main()
