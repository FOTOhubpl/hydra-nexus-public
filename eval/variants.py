def make_variant(src: Path, dst: Path, mutations: list[str], rng: random.Random, extra_har: Path | None = None,
                 as_zip: bool = False) -> tuple[Path, list[str]]:
    if dst.exists():
        shutil.rmtree(dst)
    shutil.copytree(src, dst)
    log = []
    for m in mutations:
        log.append(MUTATIONS[m](dst, rng))
    if extra_har is not None:
        shutil.copy2(extra_har, dst / extra_har.name)
        log.append(f"misfiled_har:{extra_har.name}")
    if as_zip:
        zp = dst.with_suffix(".zip")
        with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED) as zf:
            for p in sorted(dst.rglob("*")):
                if p.is_file():
                    zf.write(p, Path(dst.name) / p.relative_to(dst))
        shutil.rmtree(dst)
        log.append("zip")
        return zp, log
    return dst, log


